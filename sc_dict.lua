function sc_dict.get_ws_properties(ws_name)
    return sc_dict.WS_DATABASE[ws_name] or sc_dict.PUP_WS_DATABASE[ws_name] or sc_dict.SMN_BP_DATABASE[ws_name]
end

function sc_dict.get_pet_properties(pet_ability_name)
    return sc_dict.PUP_WS_DATABASE[pet_ability_name] or sc_dict.SMN_BP_DATABASE[pet_ability_name]
end

function sc_dict.find_ws_info(ws_name, weapon_hint)
    local props = sc_dict.get_ws_properties(ws_name)
    if props then
        return { name = ws_name, props = props }
    end
    return nil
end

function sc_dict.evaluate_ws_for_sc(ws_info, prev_sc)
    if not ws_info or not ws_info.props or not prev_sc then return nil end
    local combo_targets = sc_dict.SC_COMBO_MAP[prev_sc]
    if not combo_targets then return nil end

    for _, prop in ipairs(ws_info.props) do
        if combo_targets[prop] then
            return { result = combo_targets[prop] }
        end
    end
    return nil
end

function sc_dict.get_recommended_ws(job, weapon, prev_sc, profiles)
    if not prev_sc or not sc_dict.SC_COMBO_MAP[prev_sc] then return nil end
    local combo_targets = sc_dict.SC_COMBO_MAP[prev_sc]

    local priority_list = profiles[job] and profiles[job].ws_priority or {}
    for _, ws_name in ipairs(priority_list) do
        local props = sc_dict.get_ws_properties(ws_name)
        if props then
            for _, prop in ipairs(props) do
                if combo_targets[prop] then
                    return ws_name
                end
            end
        end
    end
    return nil
end

return sc_dict
